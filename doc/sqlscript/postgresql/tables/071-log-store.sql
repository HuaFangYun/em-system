/*
    071 - Log engine: log store, PostgreSQL 13+.
    Same tables and meaning as doc/sqlscript/mssql/tables/071-log-store.sql (see the value lists there). Run by
    Log Manager > Settings > Database > Prepare (embedded in Em.Api.Core) or by hand. Identifiers are quoted
    (case-sensitive). Safe to run again; nothing is ever dropped. Times are timestamptz (UTC).
*/

CREATE TABLE IF NOT EXISTS "ta_LogSchema"
(
    "cLogSchemaId"      int            NOT NULL,
    "cLogSchemaVersion" int            NOT NULL,
    "ustamp"            timestamptz(3) NOT NULL,
    CONSTRAINT "PK_LogSchema" PRIMARY KEY ("cLogSchemaId"),
    CONSTRAINT "CK_LogSchemaId" CHECK ("cLogSchemaId" = 1)
);

CREATE TABLE IF NOT EXISTS "ta_LogEvent"
(
    "cLogEventSeq"           bigint         GENERATED BY DEFAULT AS IDENTITY,
    "cLogEventTime"          timestamptz(3) NOT NULL,
    "cLogEventKind"          int            NOT NULL,
    "cLogEventLevel"         int            NOT NULL,
    "cLogEventCategory"      varchar(200)   NOT NULL,
    "cLogEventTemplate"      varchar(1000)  NULL,
    "cLogEventMessage"       varchar(4000)  NOT NULL,
    "cLogEventProperties"    text           NULL,
    "cLogEventException"     text           NULL,
    "cLogEventFingerprint"   varchar(32)    NULL,
    "cLogEventApp"           varchar(100)   NULL,
    "cLogEventAppVersion"    varchar(50)    NULL,
    "cLogEventInstance"      varchar(100)   NULL,
    "cLogEventEnvironment"   varchar(50)    NULL,
    "cLogEventTenant"        varchar(100)   NULL,
    "cLogEventTraceId"       varchar(64)    NULL,
    "cLogEventSpanId"        varchar(32)    NULL,
    "cLogEventRequestId"     varchar(100)   NULL,
    "cLogEventSessionId"     varchar(26)    NULL,
    "cLogEventUserId"        varchar(26)    NULL,
    "cLogEventAccount"       varchar(100)   NULL,
    "cLogEventActingAs"      varchar(100)   NULL,
    "cLogEventClientAddress" varchar(64)    NULL,
    "cLogEventSource"        varchar(10)    NOT NULL,
    "cLogEventSender"        int            NOT NULL,
    "cLogEventSenderId"      varchar(100)   NULL,
    "cLogEventReceived"      timestamptz(3) NOT NULL,
    CONSTRAINT "PK_LogEvent" PRIMARY KEY ("cLogEventSeq"),
    CONSTRAINT "CK_LogEventKind" CHECK ("cLogEventKind" IN (0, 1, 2)),
    CONSTRAINT "CK_LogEventLevel" CHECK ("cLogEventLevel" BETWEEN 0 AND 5)
);
CREATE INDEX IF NOT EXISTS "IX_LogEventTime" ON "ta_LogEvent" ("cLogEventTime");
CREATE INDEX IF NOT EXISTS "IX_LogEventKindLevel" ON "ta_LogEvent" ("cLogEventKind", "cLogEventLevel", "cLogEventTime");
CREATE INDEX IF NOT EXISTS "IX_LogEventRequest" ON "ta_LogEvent" ("cLogEventRequestId");
CREATE INDEX IF NOT EXISTS "IX_LogEventFingerprint" ON "ta_LogEvent" ("cLogEventFingerprint", "cLogEventTime");
CREATE INDEX IF NOT EXISTS "IX_LogEventUser" ON "ta_LogEvent" ("cLogEventUserId", "cLogEventTime");

CREATE TABLE IF NOT EXISTS "ta_LogError"
(
    "cLogErrorId"             char(26)       NOT NULL,
    "cLogErrorFingerprint"    varchar(32)    NOT NULL,
    "cLogErrorType"           varchar(300)   NOT NULL,
    "cLogErrorTopFrame"       varchar(1000)  NULL,
    "cLogErrorMessage"        varchar(2000)  NULL,
    "cLogErrorCount"          bigint         NOT NULL,
    "cLogErrorFirstSeen"      timestamptz(3) NOT NULL,
    "cLogErrorLastSeen"       timestamptz(3) NOT NULL,
    "cLogErrorLastApp"        varchar(100)   NULL,
    "cLogErrorLastAppVersion" varchar(50)    NULL,
    "cLogErrorUsers"          text           NULL,
    "cLogErrorUserCount"      int            NOT NULL DEFAULT 0,
    "cLogErrorState"          int            NOT NULL DEFAULT 1,
    "ustamp"                  timestamptz(3) NOT NULL,
    "datestamp"               timestamptz(3) NOT NULL,
    "json_object"             text           NULL,
    CONSTRAINT "PK_LogError" PRIMARY KEY ("cLogErrorId"),
    CONSTRAINT "UQ_LogErrorFingerprint" UNIQUE ("cLogErrorFingerprint"),
    CONSTRAINT "CK_LogErrorState" CHECK ("cLogErrorState" IN (1, 2, 3, 4))
);
CREATE INDEX IF NOT EXISTS "IX_LogErrorLastSeen" ON "ta_LogError" ("cLogErrorLastSeen" DESC);

CREATE TABLE IF NOT EXISTS "ta_LogIngestBatch"
(
    "cLogIngestBatchId"     varchar(64)    NOT NULL,
    "cLogIngestBatchTime"   timestamptz(3) NOT NULL,
    "cLogIngestBatchSender" varchar(100)   NULL,
    "cLogIngestBatchEvents" int            NOT NULL,
    CONSTRAINT "PK_LogIngestBatch" PRIMARY KEY ("cLogIngestBatchId")
);
CREATE INDEX IF NOT EXISTS "IX_LogIngestBatchTime" ON "ta_LogIngestBatch" ("cLogIngestBatchTime");

CREATE TABLE IF NOT EXISTS "ta_LogAudit"
(
    "cLogAuditId"            char(26)       NOT NULL,
    "cLogAuditSeq"           bigint         GENERATED BY DEFAULT AS IDENTITY,
    "cLogAuditGroup"         varchar(100)   NOT NULL,
    "cLogAuditKind"          varchar(100)   NOT NULL,
    "cLogAuditTime"          timestamptz(3) NOT NULL,
    "cLogAuditActorType"     varchar(20)    NOT NULL,
    "cLogAuditActorUserId"   varchar(26)    NULL,
    "cLogAuditActorAccount"  varchar(100)   NULL,
    "cLogAuditActingAs"      varchar(100)   NULL,
    "cLogAuditTargetType"    varchar(100)   NULL,
    "cLogAuditTargetKey"     varchar(400)   NULL,
    "cLogAuditDocNo"         varchar(100)   NULL,
    "cLogAuditSummary"       varchar(1000)  NULL,
    "cLogAuditReason"        varchar(1000)  NULL,
    "cLogAuditChanges"       text           NULL,
    "cLogAuditSnapshot"      text           NULL,
    "cLogAuditDetail"        text           NULL,
    "cLogAuditSource"        varchar(10)    NOT NULL DEFAULT 'server',
    "cLogAuditApp"           varchar(100)   NULL,
    "cLogAuditInstance"      varchar(100)   NULL,
    "cLogAuditClientAddress" varchar(64)    NULL,
    "cLogAuditRequestId"     varchar(100)   NULL,
    "cLogAuditTraceId"       varchar(64)    NULL,
    "cLogAuditSessionId"     varchar(26)    NULL,
    "cLogAuditShipState"     int            NOT NULL DEFAULT 0,
    CONSTRAINT "PK_LogAudit" PRIMARY KEY ("cLogAuditId"),
    CONSTRAINT "UQ_LogAuditSeq" UNIQUE ("cLogAuditSeq"),
    CONSTRAINT "CK_LogAuditShipState" CHECK ("cLogAuditShipState" IN (0, 1)),
    CONSTRAINT "CK_LogAuditSource" CHECK ("cLogAuditSource" IN ('server', 'client'))
);
CREATE INDEX IF NOT EXISTS "IX_LogAuditGroupTarget" ON "ta_LogAudit" ("cLogAuditGroup", "cLogAuditTargetKey", "cLogAuditTime" DESC);
CREATE INDEX IF NOT EXISTS "IX_LogAuditGroupTime" ON "ta_LogAudit" ("cLogAuditGroup", "cLogAuditTime" DESC);
CREATE INDEX IF NOT EXISTS "IX_LogAuditGroupDocNo" ON "ta_LogAudit" ("cLogAuditGroup", "cLogAuditDocNo");
CREATE INDEX IF NOT EXISTS "IX_LogAuditActor" ON "ta_LogAudit" ("cLogAuditActorUserId", "cLogAuditTime" DESC);
CREATE INDEX IF NOT EXISTS "IX_LogAuditTarget" ON "ta_LogAudit" ("cLogAuditTargetType", "cLogAuditTargetKey", "cLogAuditTime" DESC);
CREATE INDEX IF NOT EXISTS "IX_LogAuditSession" ON "ta_LogAudit" ("cLogAuditSessionId");
CREATE INDEX IF NOT EXISTS "IX_LogAuditTime" ON "ta_LogAudit" ("cLogAuditTime" DESC);
CREATE INDEX IF NOT EXISTS "IX_LogAuditShip" ON "ta_LogAudit" ("cLogAuditSeq") WHERE "cLogAuditShipState" = 1;

